create table if not exists public.kecamatan (
  id bigint generated by default as identity primary key,
  kode_kecamatan text unique not null,
  nama_kecamatan text not null,
  geojson_id text unique
);

create table if not exists public.data_jagung (
  id bigint generated by default as identity primary key,
  kecamatan_id bigint not null references public.kecamatan(id),
  tahun integer not null check (tahun between 2018 and 2025),
  luas_panen double precision not null check (luas_panen >= 0),
  produksi double precision not null check (produksi >= 0),
  produktivitas double precision not null check (produktivitas >= 0),
  unique (kecamatan_id, tahun)
);

create table if not exists public.hasil_clustering (
  id bigint generated by default as identity primary key,
  tahun integer not null check (tahun between 2018 and 2025),
  kecamatan_id bigint not null references public.kecamatan(id),
  cluster_label integer not null check (cluster_label between 0 and 4),
  is_medoid boolean not null default false,
  luas_panen double precision not null,
  produksi double precision not null,
  produktivitas double precision not null,
  silhouette double precision not null,
  dbi double precision not null,
  total_dissimilarity double precision not null,
  processed_at timestamptz not null default now(),
  unique (tahun, kecamatan_id)
);

create index if not exists idx_data_jagung_tahun on public.data_jagung(tahun);
create index if not exists idx_hasil_tahun on public.hasil_clustering(tahun);

