-- 1. Berikan hak akses penuh pada schema public ke service_role
grant usage on schema public to postgres, anon, authenticated, service_role;

-- 2. Tabel Inti (kecamatan, data_jagung, hasil_clustering)
create table if not exists public.kecamatan (
  id bigint generated by default as identity primary key,
  kode_kecamatan text unique not null,
  nama_kecamatan text not null,
  geojson_id text unique
);

create table if not exists public.data_jagung (
  id bigint generated by default as identity primary key,
  kecamatan_id bigint not null references public.kecamatan(id),
  tahun integer not null check (tahun between 2018 and 2025),
  luas_panen double precision not null check (luas_panen >= 0),
  produksi double precision not null check (produksi >= 0),
  produktivitas double precision not null check (produktivitas >= 0),
  unique (kecamatan_id, tahun)
);

create table if not exists public.hasil_clustering (
  id bigint generated by default as identity primary key,
  tahun integer not null check (tahun between 2018 and 2025),
  kecamatan_id bigint not null references public.kecamatan(id),
  cluster_label integer not null check (cluster_label between 0 and 4),
  is_medoid boolean not null default false,
  luas_panen double precision not null,
  produksi double precision not null,
  produktivitas double precision not null,
  silhouette double precision not null,
  dbi double precision not null default 0,
  total_dissimilarity double precision not null default 0,
  processed_at timestamptz not null default now(),
  unique (tahun, kecamatan_id)
);

create index if not exists idx_data_jagung_tahun on public.data_jagung(tahun);
create index if not exists idx_hasil_tahun on public.hasil_clustering(tahun);

-- 3. Tabel Tambahan (pengguna, pengaturan_peta, keterangan_klaster, pengaturan_klaster)
create table if not exists public.pengguna (
  id bigint generated by default as identity primary key,
  nama_lengkap text not null,
  username text unique not null,
  password_hash text not null,
  role text not null check (role in ('admin', 'operator')),
  status text not null default 'menunggu'
    check (status in ('menunggu', 'disetujui', 'ditolak', 'nonaktif')),
  dibuat_pada timestamptz not null default now(),
  divalidasi_pada timestamptz
);

create unique index if not exists idx_pengguna_satu_admin
  on public.pengguna (role)
  where role = 'admin';

create table if not exists public.pengaturan_peta (
  id integer primary key check (id = 1),
  c1_color text not null default '#15803d',
  c2_color text not null default '#a3e635',
  c3_color text not null default '#ea580c',
  c1_label text not null default 'Klaster 1',
  c2_label text not null default 'Klaster 2',
  c3_label text not null default 'Klaster 3',
  diperbarui_pada timestamptz not null default now()
);

create table if not exists public.keterangan_klaster (
  id bigint generated by default as identity primary key,
  tahun integer not null check (tahun between 2018 and 2025),
  klaster integer not null check (klaster between 1 and 5),
  keterangan text not null,
  diperbarui_pada timestamptz not null default now(),
  unique (tahun, klaster)
);

create table if not exists public.pengaturan_klaster (
  k integer not null check (k between 2 and 5),
  nomor integer not null check (nomor between 1 and 5),
  warna text not null,
  label text not null,
  diperbarui_pada timestamptz not null default now(),
  primary key (k, nomor),
  check (nomor <= k)
);

-- 4. Update constraint jika tabel sudah terlanjur dibuat dengan batas lama (0..2)
do $$
declare r record;
begin
  for r in
    select conname
    from pg_constraint
    where conrelid = 'public.hasil_clustering'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%cluster_label%'
  loop
    execute format('alter table public.hasil_clustering drop constraint %I', r.conname);
  end loop;
end $$;

alter table public.hasil_clustering
  add constraint hasil_clustering_cluster_label_check
  check (cluster_label between 0 and 4);

do $$
declare r record;
begin
  for r in
    select conname
    from pg_constraint
    where conrelid = 'public.keterangan_klaster'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%klaster%'
  loop
    execute format('alter table public.keterangan_klaster drop constraint %I', r.conname);
  end loop;
end $$;

alter table public.keterangan_klaster
  add constraint keterangan_klaster_klaster_check
  check (klaster between 1 and 5);

