-- 1. Akun pengelola (1 Admin + Operator hasil registrasi)
create table if not exists public.pengguna (
  id bigint generated by default as identity primary key,
  nama_lengkap text not null,
  username text unique not null,
  password_hash text not null,
  role text not null check (role in ('admin', 'operator')),
  status text not null default 'menunggu'
    check (status in ('menunggu', 'disetujui', 'ditolak', 'nonaktif')),
  dibuat_pada timestamptz not null default now(),
  divalidasi_pada timestamptz
);

-- Hanya boleh ada satu akun Admin
create unique index if not exists idx_pengguna_satu_admin
  on public.pengguna (role)
  where role = 'admin';

-- 2. Pengaturan warna & label legenda peta (selalu 1 baris, id = 1)
create table if not exists public.pengaturan_peta (
  id integer primary key check (id = 1),
  c1_color text not null default '#15803d',
  c2_color text not null default '#a3e635',
  c3_color text not null default '#ea580c',
  c1_label text not null default 'Klaster 1',
  c2_label text not null default 'Klaster 2',
  c3_label text not null default 'Klaster 3',
  diperbarui_pada timestamptz not null default now()
);

-- 3. Penjelasan manual per klaster per tahun (opsional, diisi Admin)
create table if not exists public.keterangan_klaster (
  id bigint generated by default as identity primary key,
  tahun integer not null check (tahun between 2018 and 2025),
  klaster integer not null check (klaster between 1 and 5),
  keterangan text not null,
  diperbarui_pada timestamptz not null default now(),
  unique (tahun, klaster)
);

